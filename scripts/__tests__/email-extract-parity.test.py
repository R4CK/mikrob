# --- 6. attachments (card e4eb72c9) -------------------------------------------
check("attachments: missing field -> empty list, no error",
      mod.collect_mcp_attachments({}) == ([], None))

base64_hash = __import__("hashlib").sha256(b"QQ==").hexdigest()
